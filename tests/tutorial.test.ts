import { createTutorialWorld, TUTORIAL_WILL } from '../src/presets/tutorial';
import { Game } from '../src/engine/Game';
import { parseCommand } from '../src/commands/ruleParser';
let pass = 0, fail = 0;
const ok = (c: boolean, m: string) => (c ? pass++ : fail++, console.log(c ? 'PASS' : 'FAIL', m));
const w = createTutorialWorld();
const g = new Game(w);
const han = w.agents.find((a) => a.name === TUTORIAL_WILL)!;
ok(!!han && !w.places.some((p) => p.style === 'karaoke'), `town: ${w.places.map((p) => p.name).join(', ')} · Wills ${w.agents.filter((a) => a.kind === 'person').length}`);
ok(w.missingWish(han)?.key === 'karaoke', `한별's wish: ${w.missingWish(han)?.label}`);
const c1 = parseCommand('고양이를 좋아하는 샐러리맨 소환');
const n0 = w.agents.length;
g.dispatch(c1!);
ok(w.agents.length === n0 + 1, 'mission 1: the example sentence spawns a Will');
const c8 = parseCommand('노래방 지어 줘');
ok(c8?.type === 'SPAWN_ENTITY', `mission 8: "노래방 지어 줘" parses (${c8?.type})`);
g.dispatch(c8!);
const k = w.places.find((p) => p.style === 'karaoke');
ok(!!k, `karaoke built: ${k?.name}`);
w.visitNow(han, k!);
let t = 0;
for (; t < 20 * 60 * 3 && !(w.hasThought(han, `place:${k!.id}`) || (han.ai.targetPlaceId === k!.id && han.ai.mode === 'visit')); t++) w.update(0.05);
ok(t < 20 * 60 * 3, `mission 9: 한별 reaches the karaoke in ${(t * 0.05).toFixed(0)} game minutes · thought: ${han.thoughts.map((x) => x.label).join(' / ')}`);
console.log(`=== ${pass} passed, ${fail} failed ===`);
